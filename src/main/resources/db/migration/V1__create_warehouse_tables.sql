CREATE TABLE items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    description VARCHAR(2000),
    base_price NUMERIC(19, 2) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT ck_items_name CHECK (length(trim(name)) > 0),
    CONSTRAINT ck_items_price CHECK (base_price >= 0)
);

CREATE TABLE variants (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id BIGINT NOT NULL REFERENCES items(id),
    sku VARCHAR(64) NOT NULL,
    size VARCHAR(50),
    color VARCHAR(50),
    price_override NUMERIC(19, 2),
    stock INTEGER NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uk_variants_sku UNIQUE (sku),
    CONSTRAINT ck_variants_sku CHECK (length(trim(sku)) > 0),
    CONSTRAINT ck_variants_stock CHECK (stock >= 0),
    CONSTRAINT ck_variants_price CHECK (price_override IS NULL OR price_override >= 0)
);

CREATE INDEX ix_variants_item_id ON variants(item_id);

CREATE UNIQUE INDEX uk_variants_options
    ON variants(item_id, lower(coalesce(size, '')), lower(coalesce(color, '')));

CREATE TABLE sales (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    variant_id BIGINT NOT NULL REFERENCES variants(id),
    sku_snapshot VARCHAR(64) NOT NULL,
    item_name_snapshot VARCHAR(150) NOT NULL,
    quantity INTEGER NOT NULL,
    unit_price NUMERIC(19, 2) NOT NULL,
    total_amount NUMERIC(19, 2) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT ck_sales_quantity CHECK (quantity > 0),
    CONSTRAINT ck_sales_price CHECK (unit_price >= 0),
    CONSTRAINT ck_sales_total CHECK (total_amount >= 0 AND total_amount = unit_price * quantity)
);

CREATE INDEX ix_sales_variant_id ON sales(variant_id);
